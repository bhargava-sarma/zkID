#!/usr/bin/env node
// Writes circuit/src/constants.nr from the circom prototype's format.mjs: the
// record's fixed head, SignedInfo's last two SHA-1 blocks (the digest's slot
// left open), the SHA-1 state after SignedInfo's first seven blocks, which are
// constant, and RSA's encoded message without its hash, as 120-bit limbs.
// Usage: node gen-constants.mjs [--check]   (--check: fail if the file is stale)

import fs from 'node:fs';
import { DIGEST_B64_LENGTH, DOC_HEAD, DOB_OFFSET, PAN_LENGTH, PAN_OFFSET, SIGNED_INFO, signedInfoFor } from '../pan/format.mjs';
import { pad, stateAfter } from '../pan/sha1.mjs';
import { LIMBS, LIMB_BITS, limbs } from './limbs.mjs';

const bytes = (text) => [...Buffer.from(text, 'latin1')];
const list = (values) => `[${values.join(', ')}]`;
const hexList = (values) => `[${values.map((v) => `0x${v.toString(16)}`).join(', ')}]`;

const signedInfo = Buffer.from(signedInfoFor('A'.repeat(DIGEST_B64_LENGTH)), 'latin1');
const padded = pad(signedInfo);
const digestAt = SIGNED_INFO[0].length;
const constantBlocks = Math.floor(digestAt / 64);
if (padded.length / 64 - constantBlocks !== 2) throw new Error("The digest must fall in SignedInfo's last two blocks.");
const tail = [...padded.subarray(64 * constantBlocks)];
for (let i = 0; i < DIGEST_B64_LENGTH; i++) tail[digestAt - 64 * constantBlocks + i] = 0; // the digest's slot

const head = [...bytes(DOC_HEAD[0]), ...Array(PAN_LENGTH).fill(0), ...bytes(DOC_HEAD[2])];
if (head.length !== DOB_OFFSET) throw new Error('head length');

// PKCS#1 v1.5 for a 2048-bit key: 00 01 FF..FF 00 || DigestInfo(SHA-1) || H.
// With H = 0 its lowest 160 bits are zero, so the circuit adds H to limbs 0 and 1.
const DIGEST_INFO_SHA1 = '3021300906052b0e03021a05000414';
const em = BigInt(`0x0001${'ff'.repeat(256 - 3 - 15 - 20)}00${DIGEST_INFO_SHA1}${'00'.repeat(20)}`);

const TEXT = {
  GENDER_TAG: ' gender="',
  MALE: 'MALE"',
  FEMALE: 'FEMALE"',
  TRANSGENDER: 'TRANSGENDER"',
  UID_TAG: ' uid="',
  PAN_TAG: '<PAN num="',
  VERIFIED_TAG: '" verifiedOn="',
  PAN_END: '"></PAN>',
  BASE64: 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/',
};

const out = `// Generated by gen-constants.mjs from ../pan/format.mjs. Do not edit.

// The canonical record's first ${DOB_OFFSET} bytes, up to the date of birth; the
// PAN number (bytes ${PAN_OFFSET}-${PAN_OFFSET + PAN_LENGTH - 1}) is left as 0.
pub global DOC_HEAD_LEN: u32 = ${DOB_OFFSET};
pub global PAN_OFFSET: u32 = ${PAN_OFFSET};
pub global PAN_LEN: u32 = ${PAN_LENGTH};
pub global DOC_HEAD: [u8; ${DOB_OFFSET}] = ${list(head)};

// SignedInfo: the SHA-1 state after its first ${constantBlocks} blocks, then its last two
// blocks with SHA-1 padding; the digest's ${DIGEST_B64_LENGTH} base64 characters go at byte
// ${digestAt - 64 * constantBlocks} of them (left as 0 here).
pub global SIGNED_INFO_MIDSTATE: [u32; 5] = ${hexList(stateAfter(padded, constantBlocks))};
pub global SIGNED_INFO_TAIL: [u8; 128] = ${list(tail)};
pub global DIGEST_AT: u32 = ${digestAt - 64 * constantBlocks};

// RSA's encoded message with a zero hash, in ${LIMBS} limbs of ${LIMB_BITS} bits, lowest first.
pub global EM_WITHOUT_HASH: [Field; ${LIMBS}] = ${hexList(limbs(em).map(BigInt))};

// Markup the circuit matches, and the base64 alphabet.
${Object.entries(TEXT)
  .map(([name, text]) => `pub global ${name}: [u8; ${text.length}] = ${list(bytes(text))}; // ${JSON.stringify(text)}`)
  .join('\n')}
`;

const file = new URL('./circuit/src/constants.nr', import.meta.url);
if (process.argv.includes('--check')) {
  if (fs.readFileSync(file, 'utf8') !== out) throw new Error('circuit/src/constants.nr is stale: run node gen-constants.mjs');
  console.log('constants.nr is up to date');
} else {
  fs.mkdirSync(new URL('./circuit/src/', import.meta.url), { recursive: true });
  fs.writeFileSync(file, out);
  console.log(`wrote circuit/src/constants.nr: head ${DOB_OFFSET} bytes, SignedInfo ${signedInfo.length} bytes (${constantBlocks} constant blocks)`);
}
