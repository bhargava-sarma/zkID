#!/usr/bin/env node
// Writes circuits/constants.circom from format.mjs: the record's fixed head,
// SignedInfo's last two SHA-1 blocks (the digest's slot left open), and the
// SHA-1 state after SignedInfo's first seven blocks, which are constant.
// Usage: node gen-constants.mjs [--check]   (--check: fail if the file is stale)

import fs from 'node:fs';
import { DIGEST_B64_LENGTH, DOC_HEAD, DOB_OFFSET, PAN_LENGTH, PAN_OFFSET, SIGNED_INFO, signedInfoFor } from './format.mjs';
import { pad, stateAfter } from './sha1.mjs';

const bytes = (text) => [...Buffer.from(text, 'latin1')];
const list = (values) => `[${values.join(', ')}]`;

const signedInfo = Buffer.from(signedInfoFor('A'.repeat(DIGEST_B64_LENGTH)), 'latin1');
const padded = pad(signedInfo);
const digestAt = SIGNED_INFO[0].length;
const constantBlocks = Math.floor(digestAt / 64);
if (padded.length / 64 - constantBlocks !== 2) throw new Error('The digest must fall in SignedInfo\'s last two blocks.');
const tail = [...padded.subarray(64 * constantBlocks)];
for (let i = 0; i < DIGEST_B64_LENGTH; i++) tail[digestAt - 64 * constantBlocks + i] = 0; // the digest's slot

const head = [...bytes(DOC_HEAD[0]), ...Array(PAN_LENGTH).fill(0), ...bytes(DOC_HEAD[2])];
if (head.length !== DOB_OFFSET) throw new Error('head length');

const out = `pragma circom 2.1.6;

// Generated by gen-constants.mjs from format.mjs. Do not edit.

// The canonical record's first ${DOB_OFFSET} bytes, up to the date of birth; the
// PAN number (bytes ${PAN_OFFSET}-${PAN_OFFSET + PAN_LENGTH - 1}) is left as 0.
function docHeadLength() { return ${DOB_OFFSET}; }
function panOffset() { return ${PAN_OFFSET}; }
function docHead() { return ${list(head)}; }

// SignedInfo: the SHA-1 state after its first ${constantBlocks} blocks, then its last
// two blocks with SHA-1 padding; the digest's ${DIGEST_B64_LENGTH} base64 characters go at
// byte ${digestAt - 64 * constantBlocks} of them (left as 0 here).
function signedInfoMidstate() { return ${list(stateAfter(padded, constantBlocks))}; }
function signedInfoTail() { return ${list(tail)}; }
function signedInfoDigestAt() { return ${digestAt - 64 * constantBlocks}; }
`;

const file = new URL('./circuits/constants.circom', import.meta.url);
if (process.argv.includes('--check')) {
  if (fs.readFileSync(file, 'utf8') !== out) throw new Error('circuits/constants.circom is stale: run node gen-constants.mjs');
  console.log('constants.circom is up to date');
} else {
  fs.mkdirSync(new URL('./circuits/', import.meta.url), { recursive: true });
  fs.writeFileSync(file, out);
  console.log(`wrote circuits/constants.circom: head ${DOB_OFFSET} bytes, SignedInfo ${signedInfo.length} bytes (${constantBlocks} constant blocks)`);
}
