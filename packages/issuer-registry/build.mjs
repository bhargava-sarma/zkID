#!/usr/bin/env node
// Writes registry.json from the UIDAI certificates in packages/secure-qr/certs
// (Aadhaar QRs) and DigiLocker's keys in packages/pan/keys.json (PAN records):
// for each key, the hash its circuit outputs for it and its validity window.
// Run after adding a key there; test/registry.test.ts checks the result.

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { keyHash } from '../circuit/index.mjs';
import { panKeyHash } from '../pan/keyhash.mjs';

const CERTS = new URL('../secure-qr/certs/', import.meta.url);
const { certificates } = JSON.parse(fs.readFileSync(new URL('registry.json', CERTS), 'utf8'));
const DIGILOCKER = JSON.parse(fs.readFileSync(new URL('../pan/keys.json', import.meta.url), 'utf8')).keys;
const sha256 = (bytes) => crypto.createHash('sha256').update(bytes).digest('hex');

export function entries() {
  const uidai = certificates.map((meta) => {
    const cert = new crypto.X509Certificate(fs.readFileSync(new URL(meta.file, CERTS)));
    return {
      id: meta.file.replace(/\.crt$/, ''),
      issuer: 'UIDAI',
      document: 'aadhaar',
      subject: cert.subject.split('\n').find((line) => line.startsWith('CN='))?.slice(3) ?? cert.subject,
      keyHash: keyHash(cert),
      modulus: Buffer.from(cert.publicKey.export({ format: 'jwk' }).n, 'base64url').toString('hex'),
      notBefore: Date.parse(cert.validFrom) / 1000,
      notAfter: Date.parse(cert.validTo) / 1000,
      spkiSha256: sha256(cert.publicKey.export({ type: 'spki', format: 'der' })),
      certSha256: cert.fingerprint256.replace(/:/g, '').toLowerCase(),
      source: `packages/secure-qr/certs/${meta.file}`,
    };
  });
  const digilocker = DIGILOCKER.map((key) => ({
    id: key.id,
    issuer: 'DigiLocker',
    document: 'pan',
    subject: key.subject_cn,
    keyHash: panKeyHash(key.modulus),
    modulus: key.modulus,
    notBefore: Date.parse(key.not_before) / 1000,
    notAfter: Date.parse(key.not_after) / 1000,
    spkiSha256: key.spki_sha256,
    certSha256: key.cert_sha256,
    source: 'packages/pan/keys.json',
  }));
  return [...uidai, ...digilocker];
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const registry = {
    note: "Issuer keys trusted by zkID verifiers: UIDAI's Secure QR signing keys (document aadhaar; keyHash is Anon Aadhaar's circuit pubkeyHash for the key) and DigiLocker's record signing keys (document pan; keyHash is the PAN circuit's Poseidon2 of the modulus). Generated by build.mjs; the provenance of each key is in packages/secure-qr/certs/registry.json and packages/pan/keys.json.",
    keys: entries(),
  };
  fs.writeFileSync(new URL('./registry.json', import.meta.url), JSON.stringify(registry, null, 2) + '\n');
  console.log(`registry.json: ${registry.keys.length} keys`);
}
